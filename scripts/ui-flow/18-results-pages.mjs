import { createFakeApi } from '../ui-harness/fake-api.mjs';
import { startApp, openApp } from '../ui-harness/app.mjs';
import { opfsRoot, readFile, listFolder } from '../ui-harness/opfs.mjs';
import { screenshot, runScript } from '../ui-harness/evidence.mjs';
import { readResults } from '../../core/ui/wire.ts';
import { planTree, renderSidecar } from '../../core/builder/builder.ts';
import { feedbackAdjacency } from '../ui-harness/dom.mjs';

await runScript('18-results-pages', 'Compact results, streamed file failure, explicit paged closure and reload', async ({ checks, evidence, defer }) => {
  const { check } = checks;
  const fake = createFakeApi();
  const { runId } = fake.completed();
  const record = fake.state.runs.get(runId);
  record.resultsPageLimit = 2;
  const app = await startApp({ fake }); defer(() => app.close());
  const session = await openApp(app, { hash: '#/run/' + runId + '/results' }); defer(() => session.close());
  const { page, picker, watch } = session;
  await page.waitForSelector('[data-testid="results-table"] tbody');
  const button = id => page.locator('button[data-op="' + id + '"]');
  const state = (id, value) => page.waitForFunction(({ id, value }) => document.querySelector('[data-feedback="' + id + '"]')?.getAttribute('data-state') === value, { id, value });
  const root = opfsRoot('stream-close');
  const saveId = 'results:save-copy:' + runId;
  const pagePath = '/api/runs/' + runId + '/results/pages';
  fake.failNext({ method: 'GET', path: pagePath }, 'E_INTERNAL', 'The results page could not be read.', { status: 500, skip: 1 });
  picker.queue(root + '/incomplete.json', { create: true });
  const before = fake.requests.length;
  await button(saveId).click();
  await state(saveId, 'problem');
  const attempts = fake.requests.slice(before).filter(r => r.path === pagePath);
  check('a failed second page is not retried or reported as saved', attempts.length === 2 && attempts[1].status === 500, attempts.map(r => ({ query:r.query, status:r.status })));
  const incomplete = await listFolder(page, root);
  check('a failed stream never publishes a partial results file', incomplete[0]?.size === 0, incomplete);
  check('failed Save leaves the run open and text held', record.status === 'complete' && record.textHeld);
  evidence.saveFailure = await screenshot(page, '18-results-pages-save-failed');
  picker.queue(root + '/complete.json', { create: true });
  await button(saveId).click(); await state(saveId, 'done');
  const saved = JSON.parse(await readFile(page, root + '/complete.json'));
  check('another explicit Save writes every full entry', saved.runId === runId && saved.entries.length === record.expectedCount && saved.entries.every(entry => Object.hasOwn(entry,'vendorOutputs')));
  const restored = readResults(saved);
  const restorePlan = planTree(restored, { naming:'original', destinationPrefix:'Restored', maxPathLength:260, maxComponentLength:255 });
  check('the saved copy reads back through the results parser and builder', restorePlan.entries.length === record.expectedCount &&
    restorePlan.entries.filter(entry=>entry.sidecarPath!==null).every(entry=>renderSidecar(entry.entry).includes(entry.entry.fingerprint)));
  picker.queue(root + '/complete.json');
  const oldCopy = await readFile(page, root + '/complete.json');
  await button(saveId).click(); await state(saveId, 'problem');
  check('Save refuses to overwrite an existing copy', await readFile(page, root + '/complete.json') === oldCopy);

  record.closeRemaining = 650;
  const closePath = '/api/runs/' + runId + '/close', closeId = 'run:close:' + runId;
  fake.failNext({ method:'POST', path:closePath }, 'E_INTERNAL', 'Deletion was interrupted.', { status:500, skip:1 });
  const closeBefore = fake.requests.length;
  await button(closeId).click();
  await page.locator('dialog button[data-sheet="confirm"]').click();
  await state(closeId, 'problem');
  const closeRequests = fake.requests.slice(closeBefore).filter(r=>r.path===closePath);
  check('close continues a successful partial page and stops on failure', closeRequests.length===2 && closeRequests[0].response.closed===false && closeRequests[1].status===500,closeRequests.map(r=>({status:r.status,response:r.response})));
  check('interrupted closure stays closing and text-held',record.status==='closing' && record.textHeld);
  check('Finish closing belongs to this run',await button(closeId).textContent()==='Finish closing this run');
  evidence.closeFailure = await screenshot(page,'18-results-pages-close-failed');
  await page.reload();
  await button(closeId).waitFor();
  const resumeBefore=fake.requests.length;
  await page.waitForTimeout(250);
  check('reload never resumes deletion automatically',fake.requests.slice(resumeBefore).every(r=>r.method==='GET'));
  await page.evaluate(()=>{document.documentElement.dataset.theme='dark';});
  evidence.finishDark = await screenshot(page,'18-results-pages-finish-dark');
  await button(closeId).click();
  // Whether text is held is a Run fact since the calm header (6 October 2026).
  await page.locator('[data-testid="shell-run-facts"] summary').click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="shell-run-facts"] .run-facts')?.textContent.includes('Text in the cloud: no'));
  const resumed=fake.requests.slice(resumeBefore).filter(r=>r.path===closePath);
  check('Finish closing completes only after the final server reply',record.status==='closed'&&!record.textHeld&&resumed.length===2&&resumed.at(-1).response.closed===true);
  check('closure never repeats a discarded request body',resumed.every(r=>JSON.stringify(r.body)==='{}'));
  const adjacency=await feedbackAdjacency(page);
  check('feedback remains beneath its action',adjacency.buttons.every(b=>b.ok));
  check('Results and Save never use legacy full results or manifest',fake.requests.every(r=>!r.path.endsWith('/results')&&!r.path.endsWith('/manifest')));
  check('no uncaught browser errors',watch.record.pageErrors.length===0,watch.record.pageErrors);
  check('no requests leave the local app',watch.record.external.length===0,watch.record.external);
  check('all synthetic responses satisfy the real wire guards',fake.problems.length===0,fake.problems);
  evidence.requests=fake.requests.map(r=>({method:r.method,path:r.path,query:r.query,status:r.status}));
});
